# -- user-bundle loader --------------------------------------------------

_USER_MODULE_PATH = "/particle/bundle.py"
_USER_MODULE_DIR = os.path.dirname(_USER_MODULE_PATH)
# Where the build pipeline unpacks resolved wheels. Mounted by the
# host as part of the particle's FS — same wasi:filesystem preopen
# that exposes bundle.py. Adding it to sys.path lets user code do
# `import httpx` (or any other resolved pure-Python dep) at runtime.
_DEPS_SITE_PACKAGES = "/particle/_deps/site-packages"

# Sticky cache so each tool call doesn't reparse/re-exec the bundle.
# Errors stick too: a malformed bundle gets the same error every call
# rather than retrying the broken import.
_user_module: object | None = None
_load_error: BaseException | None = None


def _load_user_module():
    """Load /particle/bundle.py through importlib.SourceFileLoader.

    SourceFileLoader bypasses sys.path entirely (we point it directly
    at the file). We still mutate sys.path so user code doing its own
    `import sibling` works for multi-file particles.
    """
    global _user_module, _load_error
    if _user_module is not None:
        return _user_module
    if _load_error is not None:
        raise _load_error

    try:
        if _USER_MODULE_DIR not in sys.path:
            sys.path.insert(0, _USER_MODULE_DIR)
        # _deps/site-packages contains the build-pipeline-resolved
        # wheels (httpx, pyjwt, …). Only added when the directory
        # actually exists — particles with no third-party deps never
        # ship the _deps tree, and a non-existent sys.path entry is
        # harmless but noise in tracebacks.
        if os.path.isdir(_DEPS_SITE_PACKAGES) and _DEPS_SITE_PACKAGES not in sys.path:
            sys.path.insert(0, _DEPS_SITE_PACKAGES)
        loader = importlib.machinery.SourceFileLoader("bundle", _USER_MODULE_PATH)
        spec = importlib.util.spec_from_loader("bundle", loader)
        if spec is None:
            raise RuntimeError(f"could not build module spec for {_USER_MODULE_PATH}")
        module = importlib.util.module_from_spec(spec)
        loader.exec_module(module)
    except BaseException as e:
        _load_error = e
        raise

    _user_module = module
    return module


def _get_particle() -> user_manifest.Particle:
    """Return the module-level `particle` instance from the user's
    bundle. The user constructs a `particle.manifest.Particle`
    dataclass at module scope; the dataclass shape carries everything
    the runtime needs (tool handlers, ping handler, credential
    declarations, capabilities) in typed form.
    """
    mod = _load_user_module()
    obj = getattr(mod, "particle", None)
    if obj is None:
        raise RuntimeError(
            "bundle.py must define a module-level `particle = Particle(...)` "
            "(import Particle from `particle.manifest`)"
        )
    if not isinstance(obj, user_manifest.Particle):
        raise RuntimeError(
            f"bundle.py `particle` must be a particle.manifest.Particle, "
            f"got {type(obj).__name__}"
        )
    return obj


def _describe(e: BaseException) -> str:
    """One-line summary for the WIT `error-detail.message` field —
    user-visible, deliberately short."""
    msg = str(e) or repr(e)
    return f"{type(e).__name__}: {msg}"


def _format_stack(e: BaseException) -> str:
    """Full Python traceback for the WIT `error-detail.stack` field —
    operator-visible; the host typically routes it to a log line
    rather than the user-facing error."""
    return "".join(traceback.format_exception(type(e), e, e.__traceback__))


def _tool_detail(e: BaseException) -> ToolErrorDetail:
    return ToolErrorDetail(message=_describe(e), stack=_format_stack(e))


def _health_detail(e: BaseException) -> HealthErrorDetail:
    return HealthErrorDetail(message=_describe(e), stack=_format_stack(e))


def _manifest_detail(e: BaseException) -> ManifestErrorDetail:
    return ManifestErrorDetail(message=_describe(e), stack=_format_stack(e))


def _log_traceback(e: BaseException) -> None:
    """Mirror the stack to wasi:cli/stderr in addition to attaching
    it to the WIT error. Belt-and-suspenders: some throw paths (e.g.,
    module-evaluation traps) never reach a WIT return, only stderr
    survives those.
    """
    traceback.print_exception(type(e), e, e.__traceback__, file=sys.stderr)


