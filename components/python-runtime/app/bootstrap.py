class Tools(ToolsProtocol):
    """Implements `particle:runtime/tools`."""

    def list_tools(self) -> list[ToolDef]:
        try:
            p = _get_particle()
        except BaseException as e:
            _log_traceback(e)
            # list-tools has no error variant — surface the load
            # failure as a recognizable tool row so the host gets a
            # readable diagnostic rather than a wasm trap.
            return [ToolDef(
                name="__particle_load_error__",
                description=_describe(e),
                input_schema_json="{}",
            )]

        out: list[ToolDef] = []
        for name, tool in p.tools.items():
            out.append(ToolDef(
                name=name,
                description=tool.description,
                input_schema_json=json.dumps(tool.input_schema),
            ))
        return out

    def call_tool(self, name: str, arguments_json: str) -> str:
        try:
            p = _get_particle()
        except BaseException as e:
            _log_traceback(e)
            raise Err(ToolError_HandlerError(_tool_detail(e)))

        tool = p.tools.get(name)
        if tool is None:
            raise Err(ToolError_NotFound())

        if not callable(tool.handler):
            raise Err(ToolError_HandlerError(ToolErrorDetail(
                message=f"tool {name!r} has no callable handler",
                stack=None,
            )))

        # Args are pre-validated host-side against the tool's input
        # schema (design doc §6 "Argument validation: host-side
        # only"). Trust them.
        try:
            args = json.loads(arguments_json)
        except Exception as e:
            raise Err(ToolError_HandlerError(ToolErrorDetail(
                message=f"argument JSON parse: {_describe(e)}",
                stack=_format_stack(e),
            )))

        try:
            result = tool.handler(args)
            if asyncio.iscoroutine(result):
                result = asyncio.run(result)
        except BaseException as e:
            _log_traceback(e)
            raise Err(ToolError_HandlerError(_tool_detail(e)))

        try:
            return json.dumps(result)
        except Exception as e:
            raise Err(ToolError_HandlerError(ToolErrorDetail(
                message=f"result is not JSON-serializable: {_describe(e)}",
                stack=_format_stack(e),
            )))


class Manifest(ManifestProtocol):
    """Implements `particle:runtime/manifest` — see the WIT for rationale.

    Called by the build pipeline (Phase 5) and by any host that wants
    to learn what credentials/tools the particle exposes. Module-
    scope `particle.*` helper calls aren't supported: under introspect
    the host wires trap stores so those surface as "not allowed
    during get-manifest" errors.
    """

    def get_manifest(self) -> ParticleManifest:
        try:
            p = _get_particle()
        except BaseException as e:
            _log_traceback(e)
            raise Err(ManifestError_BundleLoadError(_manifest_detail(e)))

        try:
            return _build_manifest_record(p)
        except BaseException as e:
            _log_traceback(e)
            raise Err(ManifestError_InvalidManifest(_manifest_detail(e)))


# Lookup tables mapping the user-facing string-literal values to the
# WIT-generated enum cases. Defined once so the conversion functions
# stay declarative.

_OAUTH2_FLOW_MAP = {
    "authorization-code":      Oauth2Flow.AUTHORIZATION_CODE,
    "authorization-code-pkce": Oauth2Flow.AUTHORIZATION_CODE_PKCE,
    "device-code":             Oauth2Flow.DEVICE_CODE,
}
_APIKEY_LOCATION_KIND_MAP = {
    "header":      ApikeyLocationKind.HEADER,
    "auth-scheme": ApikeyLocationKind.AUTH_SCHEME,
    "query-param": ApikeyLocationKind.QUERY_PARAM,
}
_SIGNING_ALGORITHM_MAP = {
    "hmac-sha256": SigningAlgorithm.HMAC_SHA256,
    "hmac-sha512": SigningAlgorithm.HMAC_SHA512,
}


def _build_manifest_record(p: user_manifest.Particle) -> ParticleManifest:
    """Lift the user-facing `Particle` dataclass into the WIT
    `ParticleManifest` record — a tree of componentize-py dataclass
    instances the WIT canonical ABI knows how to send across the host
    boundary. Type validation is handled by the user-facing dataclass
    constructors; this function only re-shapes.
    """
    if p.http is None:
        capabilities = CapabilitySet(http=None)
    else:
        capabilities = CapabilitySet(
            http=HttpCapability(allowed_hosts=list(p.http.allowed_hosts)),
        )

    return ParticleManifest(
        name=p.name,
        description=p.description,
        version=p.version,
        capabilities=capabilities,
        credentials=[_to_credential_entry(name, cred) for name, cred in p.credentials.items()],
        tools=[_to_tool_entry(name, tool) for name, tool in p.tools.items()],
    )


def _to_credential_entry(cname: str, cred: user_manifest.Credential) -> CredentialEntry:
    return CredentialEntry(
        name=cname,
        hosts=list(cred.hosts),
        required=cred.required,
        methods=[
            CredentialMethodEntry(
                name=mname,
                description=getattr(method, "description", "") or "",
                method=_to_credential_method(cname, mname, method),
            )
            for mname, method in cred.methods.items()
        ],
    )


def _to_credential_method(cname: str, mname: str, method) -> "CredentialMethod":
    """Map a user-facing method instance to the WIT variant case. The
    type discriminator is the Python class itself — no `type:` string
    needed, the dataclass identity carries the meaning."""
    if isinstance(method, user_manifest.Basic):
        return CredentialMethod_Basic()
    if isinstance(method, user_manifest.Raw):
        return CredentialMethod_Raw()
    if isinstance(method, user_manifest.OAuth2):
        try:
            mapped_flows = [_OAUTH2_FLOW_MAP[f] for f in method.flows]
        except KeyError as e:
            raise ValueError(
                f"credentials.{cname}.methods.{mname}: unknown OAuth2 flow {e}"
            )
        return CredentialMethod_Oauth2(value=Oauth2Method(
            flows=mapped_flows,
            scopes=list(method.scopes),
            authorization_url=method.authorization_url,
            token_url=method.token_url,
            device_auth_url=method.device_auth_url,
        ))
    if isinstance(method, user_manifest.ApiKey):
        loc = method.location
        if loc is None:
            return CredentialMethod_Apikey(value=ApikeyMethod(location=None))
        try:
            kind_enum = _APIKEY_LOCATION_KIND_MAP[loc.kind]
        except KeyError:
            raise ValueError(
                f"credentials.{cname}.methods.{mname}.location.kind "
                f"{loc.kind!r} not recognized"
            )
        return CredentialMethod_Apikey(value=ApikeyMethod(location=ApikeyLocation(
            kind=kind_enum,
            name=loc.name,
            scheme=loc.scheme,
        )))
    if isinstance(method, user_manifest.SigningKey):
        try:
            alg = _SIGNING_ALGORITHM_MAP[method.algorithm]
        except KeyError:
            raise ValueError(
                f"credentials.{cname}.methods.{mname}.algorithm "
                f"{method.algorithm!r} not recognized"
            )
        return CredentialMethod_SigningKey(value=SigningKeyMethod(algorithm=alg))
    raise ValueError(
        f"credentials.{cname}.methods.{mname}: unsupported method type "
        f"{type(method).__name__} — use one of Basic, OAuth2, ApiKey, "
        f"SigningKey, Raw from particle.manifest"
    )


def _to_tool_entry(tname: str, tool: user_manifest.Tool) -> ToolEntry:
    return ToolEntry(
        name=tname,
        description=tool.description,
        input_schema_json=json.dumps(tool.input_schema),
    )


class Health(HealthProtocol):
    """Implements `particle:runtime/health`."""

    def ping(self) -> PingResult:
        try:
            p = _get_particle()
        except BaseException as e:
            _log_traceback(e)
            raise Err(HealthError_HandlerError(_health_detail(e)))

        ping_fn = p.ping
        if not callable(ping_fn):
            raise Err(HealthError_NotImplemented())

        try:
            result = ping_fn()
            if asyncio.iscoroutine(result):
                result = asyncio.run(result)
        except BaseException as e:
            _log_traceback(e)
            raise Err(HealthError_HandlerError(_health_detail(e)))

        return _to_ping_result(result)


def _to_ping_result(payload: object) -> PingResult:
    """Coerce a user-returned payload into a PingResult.

    Accepts either a PingResult instance or the dict form
    `{"status": "ok|degraded|unhealthy", "message"?: str, "details"?: any}`.
    Dict form lets handlers stay free of WIT-binding imports.
    """
    if isinstance(payload, PingResult):
        return payload
    if not isinstance(payload, dict):
        raise RuntimeError(
            f"ping must return a dict or PingResult, got {type(payload).__name__}"
        )
    status_map = {
        "ok": Status.OK,
        "degraded": Status.DEGRADED,
        "unhealthy": Status.UNHEALTHY,
    }
    status_str = payload.get("status", "ok")
    if status_str not in status_map:
        raise RuntimeError(f"ping returned unknown status {status_str!r}")

    message = payload.get("message")
    details = payload.get("details")
    if details is not None and not isinstance(details, str):
        # Match the WIT contract: details is JSON, encoded as string.
        details = json.dumps(details)
    return PingResult(
        status=status_map[status_str],
        message=message,
        details=details,
    )
