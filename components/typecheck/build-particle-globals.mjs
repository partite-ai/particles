// Generates src/particle-globals.d.ts by wrapping each
// published types package in `declare module "..."` — the
// `@partite-ai/particle` manifest types plus the
// `@partite-ai/particle-*` host capabilities.
//
// The npm packages are the source of truth — they're what
// external consumers see when they install
// `@partite-ai/particle-credentials` etc. The bundled
// particle-globals.d.ts that ships inside the typecheck wasm is
// derived from them so the in-build typecheck and the IDE see
// the same surface.
//
// Run from the typecheck component directory:
//   node build-particle-globals.mjs
//
// Driven by the typecheck Makefile target.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..");

// Each entry is (specifier, path-to-package-types). Adding a new
// host capability (e.g., particle-secrets) means: drop a folder
// under js-types/, list it here, re-run the generator. Nothing
// else changes. `@partite-ai/particle` is the odd one out — it's
// the manifest types package, not a host capability.
const modules = [
  ["@partite-ai/particle",             "js-types/particle/index.d.ts"],
  ["@partite-ai/particle-credentials", "js-types/particle-credentials/index.d.ts"],
  ["@partite-ai/particle-oauth",       "js-types/particle-oauth/index.d.ts"],
  ["@partite-ai/particle-signing",     "js-types/particle-signing/index.d.ts"],
  ["@partite-ai/particle-kv",          "js-types/particle-kv/index.d.ts"],
];

const header = `// Generated by build-particle-globals.mjs. DO NOT EDIT.
//
// Type declarations for the \`@partite-ai/particle\` manifest types
// and the host-provided \`@partite-ai/particle-*\` modules. The
// typecheck wasm injects this file into every program as a
// synthetic root, so user particles get type-checking on
// \`satisfies Particle\`, \`credentials.fetcher(...)\`, \`kv.set(...)\`,
// etc. without needing to install the npm packages locally.
//
// Source of truth: each module's body comes verbatim from the
// matching published types package under js-types/ (particle/ and
// particle-*/index.d.ts). Re-run this generator (driven by the
// typecheck Makefile target) when those change.
`;

let out = header + "\n";
for (const [name, relPath] of modules) {
  const content = readFileSync(join(repoRoot, relPath), "utf8");
  // Indent every line by two spaces and trim trailing whitespace
  // so the closing `}` lands cleanly without a trailing blank.
  const indented = content.replace(/^/gm, "  ").trimEnd();
  out += `\ndeclare module "${name}" {\n${indented}\n}\n`;
}

// Note: Node-built-in modules ARE NOT stubbed here. Their types come
// from a filtered copy of `@types/node` that the build-lib-bundle
// generator pulls in alongside this file. See
// components/typecheck/build-lib-bundle.mjs and the matching server
// logic in components/typecheck/src/typecheck.ts.

writeFileSync(join(here, "src", "particle-globals.d.ts"), out);
console.log(`wrote src/particle-globals.d.ts: ${modules.length} particle modules`);
